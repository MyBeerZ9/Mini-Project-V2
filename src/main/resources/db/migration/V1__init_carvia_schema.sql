-- ==========================================================
-- V1 — Baseline schema for CARVIA car rental system
-- Matches entity column mappings exactly (Car.java, Booking.java)
-- Compatible with both PostgreSQL and H2 (MODE=PostgreSQL)
-- ==========================================================

CREATE TABLE IF NOT EXISTS cars (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_name        VARCHAR(255)            NOT NULL,
    brand           VARCHAR(255)            NOT NULL,
    model           VARCHAR(255)            NOT NULL,
    model_year      INT                     NOT NULL,
    car_type        VARCHAR(255)            NOT NULL,
    fuel_type       VARCHAR(255)            NOT NULL,
    transmission    VARCHAR(255)            NOT NULL,
    seats           INT                     NOT NULL,
    location        VARCHAR(255)            NOT NULL,
    price_per_day   DOUBLE PRECISION        NOT NULL,
    description     VARCHAR(2000),
    image_url       VARCHAR(1000),
    owner_name      VARCHAR(255)            NOT NULL,
    owner_email     VARCHAR(255)            NOT NULL,
    available       BOOLEAN                 NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP               NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS bookings (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_reference   VARCHAR(255)            NOT NULL UNIQUE,
    car_id              BIGINT                  NOT NULL REFERENCES cars(id),
    customer_name       VARCHAR(255)            NOT NULL,
    customer_email      VARCHAR(255)            NOT NULL,
    customer_phone      VARCHAR(255)            NOT NULL,
    start_date          DATE                    NOT NULL,
    end_date            DATE                    NOT NULL,
    total_days          INT                     NOT NULL,
    total_price         DOUBLE PRECISION        NOT NULL,
    status              VARCHAR(255)            NOT NULL,
    notes               VARCHAR(1000),
    created_at          TIMESTAMP               NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Composite index for the overlap-detection query used by BookingRepository
CREATE INDEX IF NOT EXISTS idx_bookings_car_dates_status
    ON bookings (car_id, start_date, end_date, status);
