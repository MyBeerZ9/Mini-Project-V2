ALTER TABLE bookings ADD COLUMN IF NOT EXISTS actual_return_at TIMESTAMP;
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS escalation_reason VARCHAR(500);

-- 4. Vehicle Inspections table (Pre-Trip / Post-Trip Proof)
CREATE TABLE IF NOT EXISTS vehicle_inspections (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id              BIGINT                  NOT NULL REFERENCES bookings(id),
    inspection_type         VARCHAR(32)             NOT NULL, -- PRE_TRIP, POST_TRIP
    odometer_km             INT                     NOT NULL,
    fuel_or_battery_percent INT                     NOT NULL,
    condition_notes         VARCHAR(1000),
    evidence_hash           VARCHAR(128)            NOT NULL,
    inspected_by            VARCHAR(128)            NOT NULL,
    inspected_at            TIMESTAMP               NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_inspections_booking ON vehicle_inspections(booking_id);

-- 5. Custody Alerts table (Theft Hold / Overdue SLA / Geofence breach)
CREATE TABLE IF NOT EXISTS custody_alerts (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id              BIGINT                  NOT NULL REFERENCES bookings(id),
    alert_type              VARCHAR(64)             NOT NULL, -- OVERDUE_SLA, GEOFENCE_BREACH, TRACKER_OFFLINE, THEFT_SUSPECTED
    severity                VARCHAR(32)             NOT NULL, -- LOW, MEDIUM, HIGH, CRITICAL
    location_snapshot       VARCHAR(255),
    details                 VARCHAR(1000),
    resolved                BOOLEAN                 NOT NULL DEFAULT FALSE,
    created_at              TIMESTAMP               NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_custody_alerts_booking ON custody_alerts(booking_id);
