-- 1. Create partners table
CREATE TABLE IF NOT EXISTS partners (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partner_name            VARCHAR(255)            NOT NULL,
    partner_code            VARCHAR(64)             NOT NULL UNIQUE,
    contact_email           VARCHAR(255)            NOT NULL,
    contact_phone           VARCHAR(64)             NOT NULL,
    city                    VARCHAR(128)            NOT NULL,
    revenue_share_percent   DOUBLE PRECISION        NOT NULL DEFAULT 80.0,
    verified                BOOLEAN                 NOT NULL DEFAULT TRUE,
    active                  BOOLEAN                 NOT NULL DEFAULT TRUE,
    created_at              TIMESTAMP               NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Extend cars with partner & compliance & rate bands
ALTER TABLE cars ADD COLUMN IF NOT EXISTS partner_id BIGINT;
