ALTER TABLE cars ADD COLUMN IF NOT EXISTS puc_expiry_date DATE;
ALTER TABLE cars ADD COLUMN IF NOT EXISTS permit_expiry_date DATE;
ALTER TABLE cars ADD COLUMN IF NOT EXISTS min_rate_floor DOUBLE PRECISION;
ALTER TABLE cars ADD COLUMN IF NOT EXISTS max_rate_ceiling DOUBLE PRECISION;

CREATE INDEX IF NOT EXISTS idx_cars_partner ON cars(partner_id);

-- 3. Extend bookings with KYC, Risk, Custody & Theft Hold Fields
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS kyc_status VARCHAR(32) DEFAULT 'VERIFIED';
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS renter_dl_number VARCHAR(64);
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS renter_risk_score INT DEFAULT 15;
